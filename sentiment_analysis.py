def preprocess_text(texts, tokenizer, max_length= 512):
    texts=[str(text) for text in texts]
    encoding=tokenizer(
      texts,
      padding=True,
      truncation=True,
      max_length=max_length,
      return_tensors="pt",
      return_attention_mask=True
    )
    return encoding

