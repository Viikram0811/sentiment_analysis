from tqdm import tqdm

# Define your loss function

# Example: Class weights based on your dataset distribution
# For example, class weights for [Negative, Neutral, Positive]
class_weights = torch.tensor([1.0, 1.0, 2.0]).to(device)  # Adjust weights as needed
loss_fn = nn.CrossEntropyLoss(weight=class_weights)

# Initialize the BERT model
model = BertForSequenceClassification.from_pretrained('bert-base-uncased', num_labels=3)
model.to(device)

# Define the optimizer
optimizer = AdamW(model.parameters(), lr=2e-5)

# Training loop with the updated loss function
num_epochs = 3
for epoch in range(num_epochs):
    model.train()
    total_loss = 0
    for batch in tqdm(train_loader, desc=f"Epoch {epoch+1}/{num_epochs}"):
        batch = {k: v.to(device) for k, v in batch.items()}
        labels = batch['labels']

        optimizer.zero_grad()

        outputs = model(**batch)
        logits = outputs.logits

        # Compute loss with class weights
        loss = loss_fn(logits, labels)
        total_loss += loss.item()

        # Backward pass and optimizer step
        loss.backward()
        optimizer.step()

    avg_loss = total_loss / len(train_loader)
    print(f"Epoch {epoch+1} Loss: {avg_loss:.4f}")

